#!/usr/bin/env python3
"""Build web/samples.js from the FreePats CC0 kit.

The web demo is a self-contained static page, so the 10 samples used by the
hybrid engine are embedded as base64. CC0 permits this; the provenance record
for the original WAV files is in prototype/freepats-cc0-kit/PROVENANCE.md and
assets/provenance.csv.

Run from the project root:
    python web/build_samples.py
"""

from __future__ import annotations

import base64
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
KIT = ROOT / "prototype" / "freepats-cc0-kit" / "samples"
EXTRA = ROOT / "assets" / "cc0-extra"

# (output name, path, source note)
SAMPLES = [
    ("Kick06.wav", KIT / "Kick06.wav", "FreePats"),
    ("Snare09.wav", KIT / "Snare09.wav", "FreePats"),
    ("LowTom02-01.wav", KIT / "LowTom02-01.wav", "FreePats"),
    ("MidTom02-01.wav", KIT / "MidTom02-01.wav", "FreePats"),
    ("HighTom02-01.wav", KIT / "HighTom02-01.wav", "FreePats"),
    ("Clap01.wav", KIT / "Clap01.wav", "FreePats"),
    ("Claves01.wav", KIT / "Claves01.wav", "FreePats"),
    ("Cymbal02.wav", KIT / "Cymbal02.wav", "FreePats"),
    ("OpenHiHat02-01.wav", KIT / "OpenHiHat02-01.wav", "FreePats"),
    ("ClosedHiHat01-01.wav", KIT / "ClosedHiHat01-01.wav", "FreePats"),
    ("bd_808.flac", EXTRA / "bd_808.flac", "Sonic Pi / Freesound EKVelika 208447"),
]

meta = {
    "name": "FreePats Synthesizer Percussion + Sonic Pi CC0 808 kick",
    "url": "https://freepats.zenvoid.org/Percussion/electric-percussion.html",
    "license": "CC0 1.0 Universal",
    "downloaded": "2026-10-20",
}


def main() -> None:
    lines = [
        "/* Generated by web/build_samples.py — do not edit by hand. */",
        "/* Samples: FreePats Synthesizer Percussion (CC0 1.0), "
        "https://freepats.zenvoid.org/Percussion/electric-percussion.html",
        " * plus Sonic Pi's CC0 bd_808 (Freesound EKVelika sound 208447). */",
        f"window.HYBRID_SAMPLE_META = {json.dumps(meta, ensure_ascii=False)};",
        "window.HYBRID_SAMPLES_B64 = {",
    ]
    total = 0
    for name, path, note in SAMPLES:
        raw = path.read_bytes()
        total += len(raw)
        b64 = base64.b64encode(raw).decode("ascii")
        lines.append(f'  {json.dumps(name)}: "{b64}",')
        print(f"{name:28s} {len(raw):8d} bytes -> {len(b64):9d} b64  ({note})")
    lines.append("};")
    lines.append(f"window.HYBRID_SAMPLES_TOTAL_BYTES = {total};")
    out = HERE / "samples.js"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size / 1e6:.2f} MB, raw {total / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()
